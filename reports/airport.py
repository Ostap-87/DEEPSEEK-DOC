# --- editorial splits: keep every page within the print area -----------------
def _split(title, idx, new_title=None):
    for i, p in enumerate(REPORT["pages"]):
        if p.get("title") == title:
            head, tail = p["blocks"][:idx], p["blocks"][idx:]
            if new_title is None:
                # reuse the leading sub-head as the page title
                if tail and tail[0].get("t") == "h":
                    new_title = tail[0]["x"].replace(":", "")
                    tail = tail[1:]
            REPORT["pages"][i:i + 1] = [dict(p, blocks=head), {"title": new_title, "blocks": tail}]
            return
    raise KeyError(title)


